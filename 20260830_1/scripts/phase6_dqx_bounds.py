"""Phase6: DQX規模のバウンディング（独立制約からの上下限）。推測値ではなく感度表。"""
MMO = {"FY2013.3":111,"FY2014.3":200,"FY2022.3":622,"FY2025.3":555,"FY2026.3":410}  # 億円 [Fact]

# DQX 実効月額（税込）: 30日券 1200/1400/1500、90日券は1167/1367/1467相当
ARPU = [1167, 1200, 1300, 1400, 1500]
N = [100_000, 150_000, 200_000, 250_000, 300_000, 400_000]

print("DQX 継続課金のみの年間売上（億円） 行=課金アカウント数, 列=実効月額(税込)")
print("N \\ ARPU," + ",".join(f"¥{a}" for a in ARPU))
for n in N:
    row = [f"{n*a*12/1e8:.1f}" for a in ARPU]
    print(f"{n:,}," + ",".join(row))

print()
print("MMO FY2026.3=410億 に対する構成比(%)")
print("N \\ ARPU," + ",".join(f"¥{a}" for a in ARPU))
for n in N:
    row = [f"{n*a*12/1e8/410*100:.1f}" for a in ARPU]
    print(f"{n:,}," + ",".join(row))

