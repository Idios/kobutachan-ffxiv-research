#!/usr/bin/env python3
"""
Phase 12 — 利用者からの疑義に対する検証（第12次）

【何を検証したか】
  A. 値上げ告知のリードタイムは本当に 0〜30日か     → **誤り。25〜127日、中央値30日**
  B. 「ベテランが去っている」という英語圏の通説は正しいか → **率と絶対数の混同**
  C. 「日本が最も定着している」の因果の向き          → **逆かもしれない**
  D. 公表値 95万 と本レポートの 85.4万 の差はどこから来るか

使い方: python3 scripts/phase12_claims.py
"""
import csv, sys, math, statistics as st
sys.path.insert(0, 'scripts')

W = 92
def hdr(t): print("\n" + "=" * W); print(t); print("=" * W)

PRICE = 'data/external/mmo_price_change_events.csv'
CENSUS = 'data/census_normalized.csv'


def lead_times():
    """イベント単位で重複を除いたリードタイム（既存契約者基準）"""
    seen, out = set(), []
    for r in csv.DictReader(open(PRICE)):
        if not r['lead_days_existing']:
            continue
        k = (r['title'], r['announce_date'])
        if k in seen:
            continue
        seen.add(k)
        out.append((r['title'], r['announce_date'], r['date'],
                    int(r['lead_days_existing'])))
    return sorted(out, key=lambda x: x[3])


def main():
    hdr("A. 値上げ告知のリードタイム — 「0〜30日」は誤りだった")
    print("""  v1.x は「値上げは発表から実施まで 0〜30日でほぼ観測不可能」と書いていた。
  根拠は RuneScape の2件で、うち1件を「発表と実施が同日」と読んでいた。
  **これは誤読である。** 公式告知の原文は次の通り:

    "The new pricing will roll out from 10 March 2026 for **new agreements**.
     For 12-month and 1-month members, the new pricing will apply
     at your renewal date **from 9 April 2026**."

  **同日に価格が変わったのは新規契約だけで、既存会員には30日の猶予があった。**
  FFXIV の問いは「既存の課金者がいつ値上げを食らうか」なので、参照すべきは後者である。
""")
    lt = lead_times()
    print(f"  {'タイトル':<18s}{'発表':>12s}{'既存への適用':>14s}{'リードタイム':>12s}")
    for t, a, d, n in lt:
        print(f"  {t:<18s}{a:>12s}{d:>14s}{n:>10d}日")
    v = [n for *_, n in lt]
    print(f"""
  n={len(v)}、**中央値 {st.median(v):.0f}日、レンジ {min(v)}〜{max(v)}日。0日の事例はゼロ。**

  → **「予兆観測はほぼ不可能」は撤回する。** 実務上は最短でも約{min(v)}日あり、
     **スクウェア・エニックス自身の日本での前例（DQX）は127日前の告知**である。
     監視は十分に可能である。

  【法的・契約的な下限は存在しない】
  - 特定商取引法の「特定継続的役務提供」は7業種の限定列挙でオンラインゲームを含まない
  - 民法548条の4（定型約款の変更）は「効力発生時期の到来前に周知」を求めるだけで日数の定めがない
  - FFXIV 利用規約 第6条2項・スクエニアカウント規約 第4条も「効力発生日を周知する」のみ
  → **理論上は0日も可能。だが実測は{min(v)}日を下回っていない。**""")

    hdr("B. 「ベテランが去っている」— 率と絶対数の混同である")
    print("""  英語圏では「新規・復帰は増えているのにベテランが去っている」という読みが支配的である
  （例: mein-mmo 2025-07「継続キャラが 6.2 の89万から 7.2 の74万へ」）。
  **本レポートの結論（崩れたのは新規獲得で、定着率の劣化には証拠がない）と正面から食い違う。**

  **解消は単純である。継続キャラの「数」と「率」は別物だからである。**
      継続数_t = 総数_{t−1} × 再捕捉率
  **再捕捉率が一定でも、母集団（総数_{t−1}）が縮めば継続数は減る。**
""")
    rows = [r for r in csv.DictReader(open(CENSUS)) if r['continuing_scaled']]
    print(f"  {'日付':<12s}{'前回総数':>12s}{'継続':>11s}{'再捕捉率':>10s}")
    prev = None
    rr = []
    for r in rows:
        tot = float(r['raw_total'])
        if prev and r['regime'] == prev[1]:      # 足切り基準をまたぐペアは除外
            rate = float(r['continuing_scaled']) / prev[0]
            rr.append((r['date'], prev[0], float(r['continuing_scaled']), rate))
        prev = (tot, r['regime'])
    for d, p_, c, rate in rr[-6:]:
        print(f"  {d:<12s}{p_:>12,.0f}{c:>11,.0f}{rate:>10.1%}")
    early = [x[3] for x in rr[:12]]
    late = [x[3] for x in rr[-12:]]
    print(f"""
  再捕捉率: 初期12ペアの平均 {st.mean(early):.1%} → 直近12ペアの平均 {st.mean(late):.1%}
  → **率はほぼ動いていない。** 継続数が減ったのは母集団が縮んだからである。
     **「ベテランが去っている」と「定着率は劣化していない」は矛盾しない。**
     前者は絶対数の話、後者は率の話であり、**両方とも正しい。**""")

    hdr("C. 「日本が最も定着している」— 因果の向きが逆かもしれない")
    print("""  フロー比率は JP 14.3% / NA 35.8% / EU 41.2% で、日本が最も低い（順序のみ有意）。
  これを「日本が定着的だから」と読んでいたが、**説明できる証拠が取れたのは2つだけ**で、
  **そのうち有力なほうは因果が逆である。**

  【支持される説明1】オセアニアの高さは開始時期で説明できる
    オセアニアDC「Materia」の稼働は **2022年1月25日**。それ以前は北米DCに間借りしていた。
    観測期間の大部分でオセアニアは実質的な新規市場だったので、φ_OCE=64.3% は自然である。

  【支持される説明2 — 因果が逆】北米・欧州の高さは2021年の一回性の流入で説明できる
    2021年の急増は **日本以外に偏っていた**（同時代の報道が "particularly outside of Japan" と明記）。
    要因は WoW『シャドウランド』からの流出と、英語圏配信者による集中的な露出である。
    **フロー比率は観測期間の平均**なので、北米・欧州だけが大規模な一回性流入を経験していれば、
    φ_NA・φ_EU が高く出るのは当然である。
    → **「日本が特別に定着している」ではなく「北米・欧州が2021年に特別に流入した」**
       のほうが証拠が直接的である。**これは「日本は落ちたら戻りにくい」という含意を弱める。**

  【明確に反証された説明】サービス開始時期の差（JP/NA/EU）
    1.0 は 2010-09-30、新生は 2013-08-27 で、**日米欧とも同日サービスインである。**
    開始時期の差で JP/NA/EU の違いを説明することはできない。

  【根拠が見つからなかった説明 — 書いてはならない】
    新生時の地域差 / FF ブランドの国内浸透度・FFXI からの継続層 /
    プレイ環境の差（PS 比率。**地域別のプラットフォーム構成比は非公開**）/
    決済の摩擦 / コミュニティ構造（FC・固定）/ 日本市場全体の新規流入傾向
    → いずれも一次資料が1件も見つからなかった。**もっともらしいが、根拠がない。**

  【弱いが取れた材料】日本の PC 側の入口は構造的に細い
    日本の Steam 認知率 13.3% / 利用経験率 6.2%（2025年、n=15,829）。
    ただし **FFXIV の地域別 PS/PC 構成比が非公開**なので、寄与度は定量化できない。""")

    hdr("D. 公表値 95万 と本レポートの 85.4万 の差はどこから来るか")
    last = rows[-1]
    print(f"""  読者が最初に突き当たる数字なので明示する。**同じ調査の、違う数え方である。**

  | | 値 | 何をしているか |
  |---|---|---|
  | 国勢調査の公表値 | **95万**（正確には {int(float(last['raw_total'])):,}） | {last['date']} の調査が拾った実数。**調査の間隔は {last['window_days']}日** |
  | 本レポートの値 | **85.4万** | それを **64日間隔に換算**した値 |

  **調査の間隔は 35〜123日とばらついており、間隔が長いほど多くのキャラを拾う。**
  そのまま並べると「間隔が長い回だけ人が増えた」ように見えるので、
  **すべての回を64日相当に揃えている。** {last['date']} は間隔が {last['window_days']}日と長いため、
  換算すると下がる。**人数が違うのではなく、物差しを揃えただけである。**

  → **時点どうしを比べるときは換算後の値を使う。** 公表値をそのまま並べてはいけない。""")


if __name__ == "__main__":
    main()
