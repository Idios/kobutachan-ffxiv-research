# 「8.0 を機に劣化する」という仮説なら、発売までは Base と一致し、発売前には分離しない。
def sim_bear_from_e8():
    s = K1_NOW; t = date(2026, 7, 20); out = [(t, s)]; since = None
    while t < date(2030, 3, 1):
        t2 = t + timedelta(days=64)
        I = I_BASE_LV80
        if t < E8_ASSUMED <= t2 or t < D9 <= t2: I *= LAUNCH_MULT; since = 0
        elif since is not None and since < 2: I *= UNDERSHOOT; since += 1
        rho = RHO_LV80 * RHO_BEAR_RATIO if t2 > E8_ASSUMED else RHO_LV80
        s = rho * s + I; out.append((t2, s)); t = t2
    return out


